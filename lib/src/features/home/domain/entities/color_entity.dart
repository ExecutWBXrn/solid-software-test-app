/// Color Entity
class ColorEntity {
  /// alpha color (opacity)
  final int alpha;

  /// red color
  final int red;

  /// blue color
  final int blue;

  /// green color
  final int green;

  /// initializer
  ColorEntity({
    required this.alpha,
    required this.red,
    required this.blue,
    required this.green,
  });
}
